    SET NOCOUNT ON;
    DECLARE @IDTIPOUSUARIO NVARCHAR(50);

    SELECT @IDTIPOUSUARIO = IDTIPOUSUARIO
    FROM USUARIO
    WHERE IDUSUARIO = @username AND CONTRA = @password AND ESTADO = 'Activo';

    IF @IDTIPOUSUARIO IS NOT NULL
        SELECT CAST(1 AS BIT) AS is_valid,
            CASE @IDTIPOUSUARIO
                WHEN '1' THEN 'vendedor'
                WHEN '2' THEN 'almacen'
                WHEN '3' THEN 'administrador'
                ELSE 'vendedor'
            END AS role;
    ELSE
        SELECT CAST(0 AS BIT) AS is_valid, 'vendedor' AS role;
END;
GO

PRINT 'Esquema DecoCake Shop creado.';
GO
