CREATE FUNCTION dbo.fn_fecha_ddmmyyyy()
RETURNS CHAR(8)
AS
BEGIN
    RETURN (
        RIGHT('0' + CAST(DAY(GETDATE()) AS VARCHAR(2)), 2) +
        RIGHT('0' + CAST(MONTH(GETDATE()) AS VARCHAR(2)), 2) +
        CAST(YEAR(GETDATE()) AS VARCHAR(4))
    );
END;
GO

CREATE FUNCTION dbo.fn_actor()
RETURNS NVARCHAR(50)
AS
BEGIN
    RETURN ISNULL(TRY_CAST(SESSION_CONTEXT(N'IDUSUARIO') AS NVARCHAR(50)), N'sistema');
END;
GO

